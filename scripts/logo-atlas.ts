/**
 * One prebuilt logo atlas for the L1 skills and certification walls (perf PR D, owner item 5): the walls
 * load one content-hashed WebP instead of fetching every logo under public/tech and drawing it into a
 * canvas at runtime. Each logo is drawn by headless Chromium with the exact canvas code the runtime used
 * (128 px cells, 6% padding, contain fit, centered) and Chrome's GPU raster on macOS, so the cells match
 * what Chrome drew before. The canvas pixels (straight alpha, as WebGL received them) are rounded to a
 * coarser grid that looks the same (`quantize`) and stored as lossless WebP: about 41% fewer bytes than the
 * exact pixels, where lossy WebP (4:2:0 chroma) visibly smears thin colored edges.
 *
 *   bun scripts/logo-atlas.ts          regenerate public/atlas/logos.<hash>.webp, src/experience/logo-atlas.ts
 *                                      (the hashed file name the runtime reads) and scripts/logo-atlas.lock.json
 *                                      (build-side logo order and sources hash)
 *   bun scripts/logo-atlas.ts --check  fail when the committed atlas misses a logo, a logo file changed or the
 *                                      quantization, encode or rasterize settings changed (bun run build)
 *
 * Generated files are committed (like scripts/troika-fonts.ts): the build needs no browser, the dev
 * server serves them as is, and the output only changes when a wall logo does.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { buildExperienceData } from "@/content/experience";
import { LOCALES, type Locale } from "@/content/locales";
import { ATLAS_CELL, atlasLayout, atlasPad, wallLogoSrcs, type AtlasLayout } from "@/experience/floors/lobby/logoAtlas";

const root = process.cwd();
const PUBLIC = path.join(root, "public");
const OUT = path.join(PUBLIC, "atlas");
const MANIFEST = path.join(root, "src", "experience", "logo-atlas.ts");
const LOCK = path.join(root, "scripts", "logo-atlas.lock.json");

/**
 * The client manifest, bundled into the 3D path as one string constant (src/experience/logo-atlas.ts):
 * only the hashed file name. The walls derive the layout from content at runtime
 * (`atlasLayout(wallLogoSrcs(data))`), the same order `expectedLayout` draws.
 */
export interface LogoAtlasManifest {
  /** Public URL of the atlas image (content-hashed name). */
  file: string;
}

/** Source of src/experience/logo-atlas.ts. */
export const manifestSource = (manifest: LogoAtlasManifest) =>
  `/** Generated by scripts/logo-atlas.ts (bun run logo:atlas): the prebuilt L1 wall logo atlas. Do not edit. */\nexport const LOGO_ATLAS_FILE = ${JSON.stringify(manifest.file)};\n`;

/** Reads src/experience/logo-atlas.ts back; null when it is missing or not in the generated shape. */
export function readManifest(file = MANIFEST): LogoAtlasManifest | null {
  if (!existsSync(file)) return null;
  const source = readFileSync(file, "utf8");
  const match = source.match(/LOGO_ATLAS_FILE = ("[^"]*");/);
  const manifest = match ? { file: JSON.parse(match[1]) as string } : null;
  return manifest && manifestSource(manifest) === source ? manifest : null;
}

/** Build-side record of what the committed atlas was made from (never bundled). */
export interface LogoAtlasLock {
  /** The atlas this record belongs to. */
  file: string;
  /** Logo paths in cell order when the atlas was generated. */
  srcs: string[];
  /** `sourcesHash` when the atlas was generated. */
  sources: string;
}

/** Bump when `rasterize` draws differently, so `--check` fails until the atlas is regenerated. */
export const RASTER_VERSION = 1;

/** Grid steps of `quantize`: RGB of SVG cells, RGB of raster cells (already lossy sources), partial alpha. */
export const QUANT = { svg: 4, raster: 8, alpha: 5 } as const;

/**
 * Lossless WebP encode. exact: keep the RGB of transparent pixels, which texture filtering blends into logo
 * edges. effort 6 with quality 100 is the slowest, smallest lossless setting (cwebp -z 9).
 */
export const WEBP = { lossless: true, exact: true, effort: 6, quality: 100 } as const;

const sha = (data: Buffer | string) => createHash("sha256").update(data).digest("hex");

/** The atlas layout of today's content: the same logo order the walls compute at runtime. */
export function expectedLayout(locale: Locale = "en"): AtlasLayout {
  const data = buildExperienceData(locale, { L1: "Lobby", L2: "Career", L3: "Labs", L4: "Library", RF: "Roof" });
  return atlasLayout(wallLogoSrcs(data), ATLAS_CELL);
}

/** Hash of everything the atlas pixels depend on: grid, padding, raster, quantization and encode settings, every logo (path and bytes). */
export function sourcesHash(layout: AtlasLayout, publicDir = PUBLIC): string {
  const settings = JSON.stringify({ raster: RASTER_VERSION, quant: QUANT, webp: WEBP });
  const h = createHash("sha256").update(`${layout.cell}:${atlasPad(layout.cell)}:${layout.cols}x${layout.rows}:${settings}\n`);
  for (const src of layout.srcs) {
    const file = path.join(publicDir, src);
    if (!existsSync(file)) throw new Error(`logo ${src} is missing under public/`);
    h.update(`${src}\n`).update(readFileSync(file)).update("\n");
  }
  return h.digest("hex").slice(0, 12);
}

/** Problems with the committed atlas against today's content and logo files; empty when it is fresh. */
export function atlasProblems(manifest: LogoAtlasManifest, lock: LogoAtlasLock, publicDir = PUBLIC): string[] {
  const layout = expectedLayout();
  const problems: string[] = [];
  const same = (srcs: readonly string[]) => JSON.stringify(srcs) === JSON.stringify(layout.srcs);
  if (!same(lock.srcs ?? [])) problems.push("the wall logos changed (srcs differ)");
  // One atlas serves every locale, so the runtime order must not depend on the locale.
  for (const locale of LOCALES) if (!same(expectedLayout(locale).srcs)) problems.push(`the wall logo order differs in ${locale}`);
  if (lock.file !== manifest.file) problems.push("scripts/logo-atlas.lock.json belongs to another atlas");
  if (problems.length === 0 && lock.sources !== sourcesHash(layout, publicDir)) problems.push("a logo file or an atlas setting changed (sources hash differs)");
  const file = path.join(publicDir, manifest.file);
  if (!existsSync(file)) problems.push(`${manifest.file} is missing`);
  else if (!manifest.file.includes(`.${sha(readFileSync(file)).slice(0, 10)}.`)) problems.push(`${manifest.file} does not match its content hash`);
  return problems;
}

export async function rasterize(layout: AtlasLayout): Promise<Buffer> {
  const { chromium } = await import("@playwright/test");
  // GPU raster, as Chrome draws a canvas on a visitor's machine (and the visual gate on macOS, e2e/visual-gate.spec.ts);
  // elsewhere the suite's SwiftShader flags (playwright.config.ts) and Skia's software raster. They differ only in the
  // anti-aliasing of SVG edges, so regenerate on macOS when you can.
  const gpu = process.platform === "darwin" && process.env.LOGO_ATLAS_GPU !== "off";
  const args = gpu ? ["--use-angle=metal", "--ignore-gpu-blocklist", "--enable-gpu"] : ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"];
  const browser = await chromium.launch({ args });
  try {
    const page = await browser.newPage();
    await page.route("http://atlas.local/**", async (route) => {
      const { pathname } = new URL(route.request().url());
      if (pathname === "/") return route.fulfill({ status: 200, contentType: "text/html", body: "<!doctype html><title>atlas</title>" });
      const file = path.join(PUBLIC, decodeURIComponent(pathname));
      if (!file.startsWith(PUBLIC) || !existsSync(file)) return route.fulfill({ status: 404 });
      const type = file.endsWith(".svg") ? "image/svg+xml" : file.endsWith(".webp") ? "image/webp" : file.endsWith(".png") ? "image/png" : "application/octet-stream";
      return route.fulfill({ status: 200, contentType: type, body: readFileSync(file) });
    });
    await page.goto("http://atlas.local/");
    const result = await page.evaluate(
      async ({ srcs, cols, rows, cell, pad }) => {
        // The runtime atlas code, unchanged (LogoQuads.tsx useAtlasTexture before the prebuilt atlas).
        const canvas = document.createElement("canvas");
        canvas.width = cols * cell;
        canvas.height = rows * cell;
        const ctx = canvas.getContext("2d")!;
        const failed: string[] = [];
        await Promise.all(
          srcs.map(
            (src, i) =>
              new Promise<void>((resolve) => {
                const img = new Image();
                img.decoding = "async";
                img.onload = () => {
                  const x = (i % cols) * cell;
                  const y = Math.floor(i / cols) * cell;
                  const box = cell - pad * 2;
                  const scale = Math.min(box / (img.naturalWidth || box), box / (img.naturalHeight || box));
                  const w = (img.naturalWidth || box) * scale;
                  const h = (img.naturalHeight || box) * scale;
                  ctx.drawImage(img, x + (cell - w) / 2, y + (cell - h) / 2, w, h);
                  resolve();
                };
                img.onerror = () => {
                  failed.push(src);
                  resolve();
                };
                img.src = src;
              }),
          ),
        );
        return { png: canvas.toDataURL("image/png"), failed };
      },
      { srcs: layout.srcs, cols: layout.cols, rows: layout.rows, cell: layout.cell, pad: atlasPad(layout.cell) },
    );
    if (result.failed.length > 0) throw new Error(`logos failed to load: ${result.failed.join(", ")}`);
    return Buffer.from(result.png.replace(/^data:image\/png;base64,/, ""), "base64");
  } finally {
    await browser.close();
  }
}

/**
 * Rounds the straight-alpha atlas pixels so lossless WebP compresses them better while the walls look the
 * same: RGB to multiples of 4 (SVG logos, smooth gradients) or 8 (raster logos), partial alpha to multiples
 * of 5 (at most 2 off; 0 and 255 stay exact). Fully transparent pixels keep RGB 0, which the straight-alpha
 * mipmaps blend into logo edges as before. Deterministic, so the same canvas gives the same file.
 */
export function quantize(rgba: Buffer, width: number, layout: AtlasLayout): Buffer {
  const out = Buffer.from(rgba);
  const raster = layout.srcs.map((src) => !src.endsWith(".svg"));
  const snap = (v: number, step: number) => Math.min(255, Math.round(v / step) * step);
  for (let p = 0; p < out.length / 4; p++) {
    const i = p * 4;
    let a = out[i + 3];
    if (a === 0) continue;
    if (a < 255) a = out[i + 3] = snap(a, QUANT.alpha);
    if (a === 0) {
      out[i] = out[i + 1] = out[i + 2] = 0;
      continue;
    }
    const x = p % width;
    const y = Math.floor(p / width);
    const cell = Math.floor(y / layout.cell) * layout.cols + Math.floor(x / layout.cell);
    const step = raster[cell] ? QUANT.raster : QUANT.svg;
    for (let c = 0; c < 3; c++) out[i + c] = snap(out[i + c], step);
  }
  return out;
}

async function generate() {
  const sharp = (await import("sharp")).default;
  const layout = expectedLayout();
  const sources = sourcesHash(layout);
  const png = await rasterize(layout);
  const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const pixels = quantize(data, info.width, layout);
  const raw = { raw: { width: info.width, height: info.height, channels: 4 as const } };
  const webp = await sharp(pixels, raw).webp(WEBP).toBuffer();
  if (!pixels.equals(await sharp(webp).ensureAlpha().raw().toBuffer())) throw new Error("the WebP atlas does not round-trip the quantized pixels");
  mkdirSync(OUT, { recursive: true });
  const name = `logos.${sha(webp).slice(0, 10)}.webp`;
  writeFileSync(path.join(OUT, name), webp);
  for (const f of readdirSync(OUT)) if (f !== name) rmSync(path.join(OUT, f));
  const manifest: LogoAtlasManifest = { file: `/atlas/${name}` };
  const lock: LogoAtlasLock = { file: manifest.file, srcs: layout.srcs, sources };
  writeFileSync(MANIFEST, manifestSource(manifest));
  writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
  const sourceBytes = layout.srcs.reduce((n, src) => n + readFileSync(path.join(PUBLIC, src)).length, 0);
  console.log(`${manifest.file}: ${layout.srcs.length} logos, ${layout.cols}x${layout.rows} cells of ${layout.cell} px, ${webp.length} bytes (sources ${sourceBytes} bytes)`);
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const manifest = readManifest();
    const missing = [...(manifest ? [] : [`${path.relative(root, MANIFEST)} is missing or edited`]), ...(existsSync(LOCK) ? [] : [`${path.relative(root, LOCK)} is missing`])];
    const problems = manifest && missing.length === 0 ? atlasProblems(manifest, JSON.parse(readFileSync(LOCK, "utf8")) as LogoAtlasLock) : missing;
    if (problems.length > 0) {
      console.error(`logo atlas is stale: ${problems.join("; ")}. Run: bun scripts/logo-atlas.ts`);
      process.exit(1);
    }
    console.log("logo atlas is fresh");
  } else {
    await generate();
  }
}
