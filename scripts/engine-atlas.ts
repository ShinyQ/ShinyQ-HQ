/**
 * The B1 Stack Halo's logo atlas: the build story's `stations.blueprint.stack` (the tools the site is built with) and
 * `stations.agents.tools` (the coding agents), one 128 px cell each, drawn and encoded exactly like the L1 wall atlas
 * (`scripts/logo-atlas.ts`). A name without a usable logo (`TEXT_ONLY_TECH`, Codex) becomes a text cell. The atlas
 * loads only on B1, so it is its own file, and its manifest is a module of the B1 chunk (never the main 3D path).
 *
 *   bun scripts/engine-atlas.ts          regenerate public/atlas/engine.<hash>.webp, src/experience/floors/engine/engine-atlas.ts
 *                                        and scripts/engine-atlas.lock.json
 *   bun scripts/engine-atlas.ts --check  fail when the committed atlas is stale (bun run build)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { getBuildStory } from "@/content/build-story";
import { getTechLogo } from "@/content/tech";
import { ATLAS_CELL, atlasLayout, type AtlasLayout } from "@/experience/floors/lobby/logoAtlas";
import { atlasFileProblems, sourcesHash, TEXT_CELL, writeAtlas } from "./logo-atlas";

const root = process.cwd();
const MANIFEST = path.join(root, "src", "experience", "floors", "engine", "engine-atlas.ts");
const LOCK = path.join(root, "scripts", "engine-atlas.lock.json");

/** What the B1 chunk needs: the file, the grid, the halo's cells (every cell, in order) and the agents' cells (the Agents bay tiles). */
export interface EngineAtlasManifest {
  file: string;
  cols: number;
  rows: number;
  cells: number;
  agents: number[];
}

export interface EngineAtlasLock {
  file: string;
  srcs: string[];
  sources: string;
}

/** Today's cells: the stack, then the agents' tools, each a logo path or a `text:` cell; names must not repeat a logo. */
export function engineAtlasLayout(): { layout: AtlasLayout; agents: number[] } {
  const { blueprint, agents } = getBuildStory().stations;
  const src = (name: string) => getTechLogo(name)?.src ?? `${TEXT_CELL}${name}`;
  const stack = blueprint.stack.map(src);
  const tools = agents.tools.map(src);
  const all = [...stack, ...tools];
  if (new Set(all).size !== all.length) throw new Error(`the B1 stack and tools repeat a logo: ${all.join(", ")}`);
  const layout = atlasLayout(all, ATLAS_CELL);
  return { layout, agents: tools.map((s) => layout.srcs.indexOf(s)) };
}

export function expectedManifest(file: string): EngineAtlasManifest {
  const { layout, agents } = engineAtlasLayout();
  return { file, cols: layout.cols, rows: layout.rows, cells: layout.srcs.length, agents };
}

export const engineManifestSource = (m: EngineAtlasManifest) =>
  `/** Generated by scripts/engine-atlas.ts (bun run engine:atlas): the B1 Stack Halo logo atlas. Do not edit. */\nexport const ENGINE_ATLAS = ${JSON.stringify(m)};\n`;

/** Problems with the committed atlas, manifest and lock against today's story and logo files; empty when fresh. */
export function engineAtlasProblems(): string[] {
  if (!existsSync(LOCK)) return [`${path.relative(root, LOCK)} is missing`];
  const lock = JSON.parse(readFileSync(LOCK, "utf8")) as EngineAtlasLock;
  const { layout } = engineAtlasLayout();
  const problems: string[] = [];
  if (JSON.stringify(lock.srcs) !== JSON.stringify(layout.srcs)) problems.push("the stack or the agents' tools changed (srcs differ)");
  else if (lock.sources !== sourcesHash(layout)) problems.push("a logo file or an atlas setting changed (sources hash differs)");
  const source = existsSync(MANIFEST) ? readFileSync(MANIFEST, "utf8") : "";
  if (source !== engineManifestSource(expectedManifest(lock.file))) problems.push(`${path.relative(root, MANIFEST)} is missing, edited or stale`);
  problems.push(...atlasFileProblems(lock.file));
  return problems;
}

async function generate() {
  const { layout } = engineAtlasLayout();
  const { file, bytes } = await writeAtlas(layout, "engine");
  const lock: EngineAtlasLock = { file, srcs: layout.srcs, sources: sourcesHash(layout) };
  writeFileSync(MANIFEST, engineManifestSource(expectedManifest(file)));
  writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(`${file}: ${layout.srcs.length} cells, ${layout.cols}x${layout.rows} of ${layout.cell} px, ${bytes} bytes`);
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const problems = engineAtlasProblems();
    if (problems.length > 0) {
      console.error(`B1 engine atlas is stale: ${problems.join("; ")}. Run: bun scripts/engine-atlas.ts`);
      process.exit(1);
    }
    console.log("B1 engine atlas is fresh");
  } else {
    await generate();
  }
}
