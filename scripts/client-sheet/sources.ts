/**
 * Writes src/app/lazy-sources.css (gitignored; `bun run build` and `bun run dev` run this first): a Tailwind
 * `@source not` for each file that only the client entries load, so the Classic sheet (globals.css) skips their
 * utilities and the client sheet (src/app/client-sheet.css, built by ./loader.mjs) carries them.
 *
 * The Classic set is every file `src/app/**` reaches through static, side-effect and dynamic imports without entering a
 * client entry; the lazy-only files are what the entries reach beyond it. A folder with no Classic file whose code files
 * are all lazy-only is skipped whole. docs/agents/performance.md ("Classic and client stylesheets") has the rules.
 *
 *   bun scripts/client-sheet/sources.ts
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { importClosure } from "../ci-plan";

/** The second stylesheet; each client entry imports it. */
export const CLIENT_SHEET = "src/app/client-sheet.css";
export const LAZY_SOURCES = "src/app/lazy-sources.css";
/** Lazy modules that import the client sheet: what only they reach is styled by it. */
export const CLIENT_ENTRIES = [
  "src/experience/Experience.tsx",
  "src/hud/PaletteHost.tsx",
  "src/hud/RoverTerminal.tsx",
  "src/hud/ask/AskChat.tsx",
  "src/components/cv/CvDialog.tsx",
  "src/components/paper/PaperDialog.tsx",
  "src/components/certs/CertDialog.tsx",
] as const;

const CODE = /\.(ts|tsx|js|jsx|mjs)$/;

export type Read = (file: string) => string | null;

export const readRepoFile: Read = (file) => {
  try {
    return statSync(file).isFile() ? readFileSync(file, "utf8") : null;
  } catch {
    return null;
  }
};

/** Repo-relative POSIX paths of the files under `dir`. */
export function filesUnder(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...filesUnder(p));
    else out.push(p);
  }
  return out;
}

/** Every page, layout, route and dev page under src/app. */
export const classicRoots = (): string[] => filesUnder("src/app").filter((f) => /\.(ts|tsx)$/.test(f));

/** What the Classic pages can load without a client entry. */
export function classicFiles(read: Read = readRepoFile): Set<string> {
  const entries = new Set<string>(CLIENT_ENTRIES);
  return importClosure(classicRoots(), (f) => (entries.has(f) ? null : read(f)));
}

/** Code files only the client entries load. */
export function lazyOnlyFiles(read: Read = readRepoFile, classic = classicFiles(read)): string[] {
  return [...importClosure([...CLIENT_ENTRIES], read)].filter((f) => CODE.test(f) && !classic.has(f)).sort();
}

/** The `@source not` paths (relative to src/app): whole folders where possible, else single files. */
export function lazySourcePaths(lazy: readonly string[], classic: ReadonlySet<string>): string[] {
  const lazySet = new Set(lazy);
  const out: string[] = [];
  const visit = (dir: string) => {
    const files = filesUnder(dir);
    const whole = files.some((f) => lazySet.has(f)) && files.every((f) => !classic.has(f) && (!CODE.test(f) || lazySet.has(f)));
    if (whole) return void out.push(dir);
    for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = path.posix.join(dir, entry.name);
      if (entry.isDirectory()) visit(p);
      else if (lazySet.has(p)) out.push(p);
    }
  };
  visit("src");
  const paths = out.map((p) => path.posix.relative("src/app", p));
  const glob = paths.find((p) => /[*?[\]{}!]/.test(p));
  if (glob) throw new Error(`client-sheet: "${glob}" has a glob character; @source would read it as a pattern`);
  return paths;
}

export function lazySourcesCss(paths: readonly string[]): string {
  return [
    "/* Generated by scripts/client-sheet/sources.ts (bun run build, bun run dev); do not edit. Only the client entries",
    "   load these files: the Classic sheet skips them and src/app/client-sheet.css carries their utilities. */",
    ...paths.map((p) => `@source not "${p}";`),
    "",
  ].join("\n");
}

if (import.meta.main) {
  const classic = classicFiles();
  const lazy = lazyOnlyFiles(readRepoFile, classic);
  const paths = lazySourcePaths(lazy, classic);
  writeFileSync(LAZY_SOURCES, lazySourcesCss(paths));
  console.log(`client-sheet: ${lazy.length} lazy-only files (${paths.length} @source not lines) in ${LAZY_SOURCES}`);
}
